/// The mark of an accent, about the middle of its letter.
type Mark = &'static [&'static [(f32, f32)]];

/// An accented letter as its letter, the accent, and how far up the accent goes: over the capital or
/// the lower case letter, or a cedilla hanging from the baseline.
fn accent(c: char) -> Option<(char, Mark, f32)> {
    const ACUTE: Mark = &[&[(-0.6, 0.0), (0.9, 1.8)]];
    const GRAVE: Mark = &[&[(-0.9, 1.8), (0.6, 0.0)]];
    const CIRCUMFLEX: Mark = &[&[(-1.5, 0.0), (0.0, 1.5), (1.5, 0.0)]];
    const TILDE: Mark = &[&[(-1.8, 0.1), (-1.1, 0.9), (-0.4, 0.9), (0.4, 0.3), (1.1, 0.3), (1.8, 1.1)]];
    const DIAERESIS: Mark = &[&[(-1.3, 0.3), (-1.3, 0.6)], &[(1.3, 0.3), (1.3, 0.6)]];
    const CEDILLA: Mark = &[&[(0.0, 0.0), (0.0, -0.8), (0.9, -1.5), (-0.3, -2.6)]];
    let base = match c.to_lowercase().next().unwrap_or(c) {
        'á' | 'à' | 'â' | 'ã' | 'ä' => 'a',
        'é' | 'è' | 'ê' | 'ë' => 'e',
        'í' | 'ì' | 'î' | 'ï' => 'ı',
        'ó' | 'ò' | 'ô' | 'õ' | 'ö' => 'o',
        'ú' | 'ù' | 'û' | 'ü' => 'u',
        'ý' => 'y',
        'ñ' => 'n',
        'ç' => 'c',
        _ => return None,
    };
    let base = if c.is_uppercase() { if base == 'ı' { 'I' } else { base.to_ascii_uppercase() } } else { base };
    let mark = match c.to_lowercase().next().unwrap_or(c) {
        'á' | 'é' | 'í' | 'ó' | 'ú' | 'ý' => ACUTE,
        'à' | 'è' | 'ì' | 'ò' | 'ù' => GRAVE,
        'â' | 'ê' | 'î' | 'ô' | 'û' => CIRCUMFLEX,
        'ã' | 'õ' | 'ñ' => TILDE,
        'ä' | 'ë' | 'ï' | 'ö' | 'ü' => DIAERESIS,
        _ => return Some((base, CEDILLA, 0.0)),
    };
    Some((base, mark, if c.is_uppercase() { 11.0 } else { 8.3 }))
}

/// A superscript figure, as the figure.
fn superscript(c: char) -> Option<char> {
    Some(match c {
        '¹' => '1',
        '²' => '2',
        '³' => '3',
        _ => return None,
    })
}

/// How much smaller a superscript figure is, and how far up it starts.
const SUP: (f32, f32) = (0.6, 4.2);

/// The width of `c`, in grid units.
pub(super) fn width(c: char) -> f32 {
    if let Some(f) = superscript(c) {
        return width(f) * SUP.0;
    }
    let c = accent(c).map_or(c, |(b, ..)| b);
    shape(c).or_else(|| shape('?')).map_or(0.0, |(w, _)| w)
}

/// The polylines of `c` in grid units, y up, from its left end on the baseline.
pub(super) fn strokes(c: char) -> Vec<Vec<(f32, f32)>> {
    if let Some(f) = superscript(c) {
        let (k, up) = SUP;
        return strokes(f).into_iter().map(|s| s.into_iter().map(|(x, y)| (x * k, up + y * k)).collect()).collect();
    }
    let (letter, mark) = accent(c).map_or((c, None), |(b, m, up)| (b, Some((m, up))));
    let Some((w, lines)) = shape(letter).or_else(|| shape('?')) else { return Vec::new() };
    let mut out: Vec<Vec<(f32, f32)>> = lines.iter().map(|s| traced(s)).collect();
    if let Some((mark, up)) = mark {
        out.extend(mark.iter().map(|s| s.iter().map(|&(x, y)| (w / 2.0 + x, up + y)).collect()));
    }
    out
}

/// A stroke's points, its arcs a point every 10 degrees or less.
fn traced(stroke: &[S]) -> Vec<(f32, f32)> {
    let mut pts = Vec::new();
    for s in stroke {
        match *s {
            P(x, y) => pts.push((x, y)),
            A(x, y, rx, ry, from, to) => {
                let n = ((to - from).abs() / 10.0).ceil().max(1.0) as usize;
                for i in 0..=n {
                    let a = (from + (to - from) * i as f32 / n as f32).to_radians();
                    pts.push((x + rx * a.cos(), y + ry * a.sin()));
                }
            }
        }
    }
    pts
}
